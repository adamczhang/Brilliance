"""mkhy4mmgolden.py OUT.h -- goldens for tests/mm_test.cpp's Hy4-flash family, every number from
transformers' own code at the Hy4-flash PR (c2ec8505; the harness venv in hy4flash/ref):
HYV4VLVideoProcessor.smart_resize, HYV4VLImageProcessorPil's patches of a picture (raster order,
as the reference emits them; the test reorders radiance's merge-block rows), and
HYV4FlashModel.get_rope_index over a prompt with a picture and a two-frame clip, newline columns
included.

Run with the harness venv:  ref/venv/bin/python tests/mkhy4mmgolden.py tests/hy4_mm_golden.h
"""
import sys, types
import numpy as np, torch
from PIL import Image

import ast, inspect, textwrap
import transformers.models.hy_v4_vl as _hyvl
from transformers.models.hy_v4_vl.image_processing_pil_hy_v4_vl import HYV4VLImageProcessorPil
from transformers.models.hy_v4_flash.modeling_hy_v4_flash import HYV4FlashModel

M64 = (1 << 64) - 1


def pix(f, y, x, c):
    """mm_test.cpp's splitmix hash of a pixel's coordinates."""
    z = (f * 0x9E3779B97F4A7C15 + y * 0xBF58476D1CE4E5B9 + x * 0x94D049BB133111EB +
         c * 0x2545F4914F6CDD1D + 12345) & M64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return (z ^ (z >> 31)) & 255


def frame(f, h, w):
    a = np.zeros((h, w, 3), dtype=np.uint8)
    for y in range(h):
        for x in range(w):
            for c in range(3):
                a[y, x, c] = pix(f, y, x, c)
    return a


def arr(name, ctype, vals, per=12):
    s = f"static const {ctype} {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def farr(name, vals, per=8):
    return arr(name, "float", [repr(float(np.float32(v))) + "f" for v in vals], per)


out = ["/* hy4_mm_golden.h -- generated by tests/mkhy4mmgolden.py (transformers c2ec8505); do not edit. */",
       "#pragma once", ""]

# ---- video smart_resize: (h, w, frames, factor, max_px, max_frame_px) -> (oh, ow). The video
# processor module imports torchvision, which the harness venv does not carry, so its static
# smart_resize is taken from the module's source as written and run on its own.
_src = open(_hyvl.__path__[0] + "/video_processing_hy_v4_vl.py").read()
_cls = next(n for n in ast.parse(_src).body
            if isinstance(n, ast.ClassDef) and n.name == "HYV4VLVideoProcessor")
_fn = next(n for n in _cls.body if isinstance(n, ast.FunctionDef) and n.name == "smart_resize")
_fn.decorator_list = []
_ns = {}
exec(compile(ast.Module(body=[_fn], type_ignores=[]), "video_processing_hy_v4_vl.py", "exec"), _ns)
class HYV4VLVideoProcessor:
    smart_resize = staticmethod(_ns["smart_resize"])

vcases = [(720, 1280, 16, 32, 33554432, 1048576), (1080, 1920, 64, 32, 33554432, 1048576),
          (480, 640, 600, 32, 33554432, 1048576), (100, 3000, 4, 32, 33554432, 1048576),
          (31, 50, 2, 32, 33554432, 1048576), (2000, 300, 8, 32, 4194304, 262144),
          (64, 96, 3, 8, 4096, 2048), (40, 72, 2, 8, 16384, 1024)]
vres = []
for h, w, t, fac, mp, mf in vcases:
    oh, ow = HYV4VLVideoProcessor.smart_resize(h, w, t, factor=fac, max_pixels=mp, max_image_size=mf)
    vres += [h, w, t, fac, mp, mf, oh, ow]
out.append(f"static const int kHyVidN = {len(vcases)};")
out.append(arr("kHyVid", "long long", vres, 8))

# ---- a picture's patches: 70 x 110 pixels, factor 32 (patch 16, merge 2), band [32*32*4, 96*96]
H, W = 70, 110
img = Image.fromarray(frame(0, H, W))
proc = HYV4VLImageProcessorPil(size={"shortest_edge": 32 * 32 * 4, "longest_edge": 96 * 96})
bf = proc(images=[img], return_tensors="np")
pv, grid = bf["pixel_values"], bf["image_grid_thw"][0].tolist()
out.append(f"static const int kHyImgH = {H}, kHyImgW = {W};")
out.append(f"static const int kHyImgGrid[3] = {{ {grid[0]}, {grid[1]}, {grid[2]} }};")
out.append(f"static const int kHyImgDim = {pv.shape[1]};")
# Every 7th value of the raster-order rows, enough to catch a wrong order, stride or constant.
flat = pv.reshape(-1)
sel = list(range(0, flat.size, 7))
out.append(f"static const int kHyImgStride = 7;")
out.append(farr("kHyImgVals", flat[sel].tolist()))

# ---- get_rope_index: 3 text, picture (grid 1 x 4 x 6), 2 text, clip (2 x 4 x 4), 2 text
merge = 2
img_grid, vid_grid = [1, 4, 6], [2, 4, 4]
n_img = (img_grid[1] // merge) * (img_grid[2] // merge + 1)
n_vid = vid_grid[0] * (vid_grid[1] // merge) * (vid_grid[2] // merge + 1)
types_ = [0] * 3 + [1] * n_img + [0] * 2 + [2] * n_vid + [0] * 2
ids = torch.zeros(1, len(types_), dtype=torch.long)
fake = types.SimpleNamespace(config=types.SimpleNamespace(
    vision_config=types.SimpleNamespace(spatial_merge_size=merge)))
fake.get_vision_position_ids = lambda *a, **k: HYV4FlashModel.get_vision_position_ids(fake, *a, **k)
pos, delta = HYV4FlashModel.get_rope_index(fake, ids, torch.tensor([types_]),
                                           image_grid_thw=torch.tensor([img_grid]),
                                           video_grid_thw=torch.tensor([vid_grid]))
out.append(f"static const int kHyRopeN = {len(types_)};")
out.append(f"static const int kHyRopeImageAt = 2, kHyRopeVideoAt = {3 + n_img + 1};"
           f"  /* each item's first token: its start marker */")
out.append(f"static const int kHyRopeDelta = {int(delta.item())};")
for c, nm in enumerate("THW"):
    out.append(arr(f"kHyRope{nm}", "int", pos[c, 0].tolist(), 16))

open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[1], "grid", grid, "delta", int(delta.item()))
