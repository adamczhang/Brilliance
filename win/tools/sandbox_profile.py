#!/usr/bin/env python3
"""Brilliance: write or check win/profiles/sandbox.yaml, the dashboard Sandbox's fleet.

    python -I win/tools/sandbox_profile.py write     regenerate it from the other profiles
    python -I win/tools/sandbox_profile.py check     exit 1 if it no longer matches them

The Sandbox tab of the dashboard (docs/GUIDE.md section 6.1) picks a model from a list and loads it
with POST /admin/models/NAME/load. The page is served by the running radiance process, so it cannot
restart radiance on another profile; instead one process serves a fleet with one entry per shipped
profile, named after it, with that profile's model keys and startup warm-up off. A request or
Sandbox Start can load an entry. Models can stay resident together when they fit. Start holds
the selected model until Stop. This file is derived from the single-model profiles.

Process-wide keys cannot differ per entry: memory.gpu-headroom-mib takes the smallest any profile
sets, scheduler.load-timeout the longest. Reads and writes files only; standard library only.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROFILES = os.path.join(ROOT, "win", "profiles")
OUT = os.path.join(PROFILES, "sandbox.yaml")
SKIP = {"sandbox.yaml"}

HEADER = """\
# Brilliance profile: the dashboard's Sandbox. GENERATED by win/tools/sandbox_profile.py from the
# other profiles in this folder; do not edit it by hand (`python -I win/tools/sandbox_profile.py write`).
#
# One radiance process serving every shipped profile as a model of its own, named after the profile,
# with startup warm-up off. A request or Sandbox Start can load an entry. Models can stay resident
# together when they fit. Start holds the selected model until Stop. For quick fleet checks, open
# the dashboard (http://127.0.0.1:8000/). To serve one model, start its own profile.
#
#   .\\serve.ps1 sandbox                    every discrete card, so every entry can load on four
#   .\\serve.ps1 sandbox -Bus 3,9           two cards: the one- and two-card entries
#
# Every entry needs as many cards as its tp. radiance refuses to start a fleet with an entry whose tp
# exceeds its cards ("tp N needs N cards"), so the launcher (serve.ps1) starts it without those
# entries and names each one it dropped. The scheduler chooses each entry's cards among the visible
# ones (docs/MULTIMODEL.md section 8.4).
# Speeds and memory are not the same as starting the profile alone: with more than one card visible,
# HIP virtual memory is off, so a one-card entry's KV cache is sized whole at load, and the pin limit
# is the one for the visible cards (SUPPORT.md, known issue 3); a load the limit refuses fails with
# the reason on the page. Process-wide settings take the smallest headroom and the longest load
# timeout any profile sets.
#
# Loopback only and no key: Start and Stop answer a browser on this machine only.
"""


def blocks(path):
    """The profile's model entry (its name and body lines) and its memory/scheduler keys."""
    lines = open(path, encoding="utf-8").read().splitlines()
    top, section, name, body = {}, None, None, []
    for ln in lines:
        if not ln.strip() or ln.lstrip().startswith("#") and section != "models":
            continue
        m = re.match(r"^([a-z-]+):\s*$", ln)
        if m:
            section = m.group(1)
            continue
        if section == "models":
            m = re.match(r"^  ([^\s#][^:]*):\s*$", ln)
            if m and name is None:
                name = m.group(1)
            elif name is not None and (ln.startswith("    ") or ln.lstrip().startswith("#")):
                body.append(ln)
            elif m:
                raise SystemExit("%s: more than one model entry" % path)
        elif section in ("memory", "scheduler"):
            m = re.match(r"^  ([a-z-]+):\s*(\S+)", ln)
            if m:
                top[(section, m.group(1))] = m.group(2)
    if name is None:
        raise SystemExit("%s: no model entry" % path)
    while body and body[-1].lstrip().startswith("#") and not body[-1].startswith("    "):
        body.pop()
    return name, body, top


def seconds(v):
    m = re.match(r"^(\d+)(ms|s|m|h)?$", v)
    if not m:
        raise SystemExit("load-timeout %r: not understood" % v)
    return int(m.group(1)) * {"ms": 0.001, "s": 1, None: 1, "m": 60, "h": 3600}[m.group(2)]


def render():
    entries, headroom, timeout = [], [], []
    for f in sorted(os.listdir(PROFILES)):
        if not f.endswith(".yaml") or f in SKIP:
            continue
        name, body, top = blocks(os.path.join(PROFILES, f))
        tp = next((int(m.group(1)) for b in body for m in [re.match(r"^\s+tp:\s*(\d+)", b)] if m), 1)
        entries.append((tp, f[:-5], name, body))
        if ("memory", "gpu-headroom-mib") in top: headroom.append(int(top[("memory", "gpu-headroom-mib")]))
        if ("scheduler", "load-timeout") in top: timeout.append(top[("scheduler", "load-timeout")])
    out = [HEADER, "server:\n  host: 127.0.0.1\n  port: 8000\n"]
    if headroom:
        out.append("memory:\n  gpu-headroom-mib: %d\n" % min(headroom))
    out.append("scheduler:\n")
    if timeout:
        out.append("  load-timeout: %s\n" % max(timeout, key=seconds))
    out.append("  warm-up: false\nmodels:\n")
    for tp, prof, name, body in sorted(entries):
        out.append("  %s:              # profiles/%s.yaml (its model: %s), %d card%s\n"
                   % (prof, prof, name, tp, "" if tp == 1 else "s"))
        out.extend(b + "\n" for b in body)
    return "".join(out)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    text = render()
    if mode == "write":
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(OUT, ROOT))
        return 0
    if mode == "check":
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("sandbox_profile: %s does not match the profiles; run `python -I win/tools/sandbox_profile.py write`"
                  % os.path.relpath(OUT, ROOT))
            return 1
        print("sandbox_profile: matches")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
