#!/usr/bin/env python
"""Golden key sets for dfly_sel (tests/ref_hy4_ops_test.cpp, WP13.2): the 210 cases of
ref/test_dfly_ref.py check (c), with the token set vLLM's own code gives every row of the block.

  HY4_REF=/root/work/claude-scratch/hy4flash/ref  $HY4_REF/venv/bin/python gen_dfly_golden.py > ../../hy4_dfly_golden.h

Per case (G, a, B, dense or selecting, the recalled closed groups): the trunk's selection snapshot at
row a-1 is vLLM's `expand_groups` (hy_v4_flash/nvidia/indexpool_ops.py) over the recalled groups, and
the draft's key set of row j is `_reference_reuse_indices` (tests/v1/spec_decode/
test_dfly_prepare_inputs.py, local window 0), both ported verbatim in test_dfly_ref.py and imported
from there, the same random draws (seed 0) in the same order. A row's set is written as sorted
half-open intervals of token positions. The test builds dfly_sel's operands from the groups (a
shuffled page map, the snapshot as qsa_select with `own` leaves it) and compares the table, expanded
through the page map and cut at `len`, with these sets. """
import os, sys
import numpy as np, torch

REF = os.environ.get("HY4_REF", "/root/work/claude-scratch/hy4flash/ref")
sys.path.insert(0, REF)
import test_dfly_ref as T

cases, recs, ivs, rows = [], [], [], []
rng = np.random.default_rng(0)
ratio = 4
for G, anchors in ((4, [1, 2, 3, 4, 5, 8, 15, 16, 17, 18, 19, 20, 21, 33, 40, 61]),
                   (512, [1, 2, 16, 17, 2047, 2048, 2049, 2052, 2053, 2054, 2055, 3000])):
    budget = G - 1
    for a in anchors:
        for B in range(2, 7):
            for kind in ("dense", "select"):
                g0 = (a - 1) // ratio
                if kind == "dense":
                    if g0 > budget: continue
                    rec = np.arange(g0)
                else:
                    k = budget if g0 > budget else int(rng.integers(0, g0 + 1))
                    rec = np.sort(rng.choice(g0, size=k, replace=False)) if k else np.array([], dtype=np.int64)
                ids = torch.full((1, budget), -1, dtype=torch.int64); ids[0, :len(rec)] = torch.from_numpy(rec.astype(np.int64))
                snap = T.expand_groups(ids, torch.tensor([a - 1]), ratio)
                width = snap.shape[1] + 0 + B + 8
                rr = T.reference_reuse_indices(snap, torch.tensor([a]), 0, torch.tensor([True]), width, B)
                row0 = len(rows)
                for j in range(B):
                    toks = sorted(set(int(v) for v in rr[j] if v >= 0))
                    iv0 = len(ivs) // 2
                    s = None
                    for t in toks:
                        if s is None: s, e = t, t + 1
                        elif t == e: e += 1
                        else: ivs.extend([s, e]); s, e = t, t + 1
                    if s is not None: ivs.extend([s, e])
                    rows.extend([iv0, len(ivs) // 2 - iv0])
                cases.extend([G, a, B, 0 if kind == "dense" else 1, len(recs), len(rec), row0 // 2])
                recs.extend(int(x) for x in rec)

def emit(name, v):
    body = ",".join("%d" % x for x in v)
    print("static const int32_t %s[%d] = {%s};" % (name, max(1, len(v)), body or "0"))

print("/* Generated by tests/data/hy4/gen_dfly_golden.py; do not edit. */")
print("#pragma once")
print("#include <stdint.h>")
print("/* per case: G, a, B, selecting, rec_off, rec_n, row_off (into kDflyRow, a pair a row) */")
print("static const int kDflyCases = %d;" % (len(cases) // 7))
emit("kDflyCase", cases); emit("kDflyRec", recs)
print("/* per row: interval offset, interval count (into kDflyIv, [lo, hi) pairs) */")
emit("kDflyRow", rows); emit("kDflyIv", ivs)
